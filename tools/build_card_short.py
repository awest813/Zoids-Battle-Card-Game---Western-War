"""Build supplemental pointer entries for short card-text fragments that the
main inventory skipped (mid-word suffixes, terrain labels, HP bonuses).

The 0x40-byte card records can reference tiny strings outside the main text
bank (0x800F6EE0..0x800F6FB0 and a few in-bank numeric strings). They are not in
TEXT_TRACKER, so they need their own TOML entries.
"""
from card_text_table import EXE, RAM_BASE, card_text_slots

b = EXE.read_bytes()

# target address -> English. Suffixes that merely complete an already-translated
# verb are hidden with a single space to avoid duplicating the sentence.
EN = {
    0x800F6F18: " ",
    0x800F6F10: " ",
    0x800F6F08: "Range 1.",
    0x800F6F00: " ",
    0x800F6EF8: "-",
    0x800F6EFC: " ",
    0x800F6EF4: "Sand",
    0x800F6EF0: "Air",
    0x800F6EE8: " ",
    0x800F6EE0: " ",
    0x800F6F50: "Melee Weak",
    0x800F6F58: "Anti-Air",
    0x800F6F20: "Acquire",
    0x800F6F28: "Search",
    0x800F6F30: "Focus",
    0x800F6F38: "Heal",
    0x800F6F40: "Obtain",
    0x800F6F48: "Transport",
    0x800F6F98: "Snake Type",
    0x800F6FA0: "Bear Type",
    0x800F6FA8: "Insect Type",
    0x80027294: "HP +600.",
    0x8002718C: "HP +300.",
    0x80025D18: "HP +200.",
}

targets = {}
for _, _, slot_address, source in card_text_slots(b):
    if source in EN:
        targets.setdefault(source, []).append(slot_address)

lines = [
    "# Supplemental card-text fragments skipped by the main inventory.",
    "# Generated by tools/build_card_short.py.",
    "schema = 1",
    'default_lang = "en"',
    'langs = ["en"]',
    "",
]
for target in sorted(targets):
    o = target - RAM_BASE
    e = b.find(b"\0", o)
    raw = b[o:e]
    jp = raw.decode("shift_jis", "replace")
    en = EN[target]
    lines += [
        "[[entry]]",
        f'src_hex = "{raw.hex()}"',
        f'src_jp = "{jp}"',
        f"src_addr = 0x{target:08x}",
        f'record_addr = 0x{target:08x}',
        f"ptr_addr = 0x{targets[target][0]:08x}",
        "ptr_addrs = [" + ", ".join(f'"0x{a:08x}"' for a in targets[target]) + "]",
        'term = "nul"',
        'pad = "none"',
        f'en = "{en}"',
        'note = "card short fragment"',
        "",
    ]

open("translations/zoids.card_short.toml", "w", encoding="utf-8").write("\n".join(lines))
print("entries", len(targets))
for t, a in sorted(targets.items()):
    print(hex(t), EN[t], [hex(x) for x in a])
